#!/usr/bin/env python3
"""Generate the standalone robot model used by the C++ whole-body controller.

  python3 tools/gen_robot_model.py            # writes src/wbc/robot_model.h and
                                              # src/wbc/wbc_default_params.h

robot_model.h holds the kinematic tree and mass properties read from the MuJoCo
model (CAD/scene.xml), so the controller core (src/wbc/rbd.cpp) can compute the
mass matrix, bias forces, Jacobians and CoM itself, without MuJoCo. This is what
lets it run on a microcontroller.

wbc_default_params.h holds the WbcParams block (LQR gain, posture table, model
indices, gains) that controllers/wbc/wbc_controller.py computes at start-up, as a
C initializer for targets that cannot run Python.

Re-run after any change to CAD/robot.xml. The Python wrapper refuses to start
the C++ backend if the generated model does not match the MuJoCo model.
"""
import argparse
import os
import sys

import numpy as np
import mujoco

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, ROOT)


def fmt(x):
    return repr(float(x))


def arr(a):
    a = np.asarray(a, dtype=float).ravel()
    return "{" + ", ".join(fmt(v) for v in a) + "}"


def arr2(a):
    return "{" + ", ".join(arr(r) for r in a) + "}"


def iarr(a):
    return "{" + ", ".join(str(int(v)) for v in np.asarray(a).ravel()) + "}"


def quat2mat(q):
    m = np.zeros(9)
    mujoco.mju_quat2Mat(m, np.asarray(q, dtype=float))
    return m.reshape(3, 3)


def model_header(m, src):
    nb = m.nbody
    jtype = np.full(nb, -1)
    qadr = np.full(nb, -1)
    dadr = np.full(nb, -1)
    axis = np.zeros((nb, 3))
    for b in range(1, nb):
        if m.body_jntnum[b] > 1:
            raise SystemExit(f"body {m.body(b).name}: more than one joint is not supported")
        if m.body_jntnum[b] == 0:
            continue
        j = m.body_jntadr[b]
        t = int(m.jnt_type[j])
        FREE, HINGE = int(mujoco.mjtJoint.mjJNT_FREE), int(mujoco.mjtJoint.mjJNT_HINGE)
        if t not in (FREE, HINGE):
            raise SystemExit(f"joint {m.joint(j).name}: only free and hinge joints are supported")
        if t == FREE and (b != 1 or m.body_parentid[b] != 0):
            raise SystemExit("the free joint must belong to body 1, a child of the world")
        if np.abs(m.jnt_pos[j]).max() > 1e-12:
            raise SystemExit(f"joint {m.joint(j).name}: joint anchor must be at the body origin")
        if t == HINGE and abs(m.qpos0[m.jnt_qposadr[j]]) > 1e-12:
            raise SystemExit(f"joint {m.joint(j).name}: non-zero ref/qpos0 is not supported")
        jtype[b] = 0 if t == FREE else 1
        qadr[b] = m.jnt_qposadr[j]
        dadr[b] = m.jnt_dofadr[j]
        axis[b] = m.jnt_axis[j]
    if jtype[1] != 0:
        raise SystemExit("body 1 must carry the free joint")
    for b in range(2, nb):
        if m.body_rootid[b] != 1:
            raise SystemExit(f"body {m.body(b).name}: only one floating robot is supported")
    for i in range(m.nu):
        if int(m.actuator_trntype[i]) != int(mujoco.mjtTrn.mjTRN_JOINT) or abs(m.actuator_gear[i, 0] - 1.0) > 1e-12:
            raise SystemExit(f"actuator {m.actuator(i).name}: only gear-1 joint motors are supported")
    inertia = np.zeros((nb, 9))
    for b in range(nb):
        Ri = quat2mat(m.body_iquat[b])
        inertia[b] = (Ri @ np.diag(m.body_inertia[b]) @ Ri.T).ravel()
    dof_body = m.dof_bodyid.copy()
    names = ", ".join(f'"{m.body(b).name}"' for b in range(nb))
    return f"""// GENERATED by tools/gen_robot_model.py from {src}. Do not edit.
// Kinematic tree and mass properties for the standalone rigid-body dynamics
// in rbd.cpp (MuJoCo conventions: free-joint linear velocity in the world
// frame, angular velocity in the body frame; quaternions w, x, y, z).
#pragma once

namespace wbc {{
namespace model {{

constexpr int NQ = {m.nq};
constexpr int NV = {m.nv};
constexpr int NU = {m.nu};
constexpr int NBODY = {nb};          // including the world (body 0)
constexpr double TOTAL_MASS = {fmt(np.sum(m.body_mass))};

// Per body. JNT_TYPE: -1 none (welded), 0 free, 1 hinge (anchor at the body origin)
constexpr const char* BODY_NAME[NBODY] = {{{names}}};
constexpr int PARENT[NBODY] = {iarr(m.body_parentid)};
constexpr int JNT_TYPE[NBODY] = {iarr(jtype)};
constexpr int QPOS_ADR[NBODY] = {iarr(qadr)};
constexpr int DOF_ADR[NBODY] = {iarr(dadr)};
constexpr double BODY_POS[NBODY][3] = {arr2(m.body_pos)};
constexpr double BODY_QUAT[NBODY][4] = {arr2(m.body_quat)};
constexpr double JNT_AXIS[NBODY][3] = {arr2(axis)};
constexpr double MASS[NBODY] = {arr(m.body_mass)};
constexpr double IPOS[NBODY][3] = {arr2(m.body_ipos)};
constexpr double INERTIA[NBODY][9] = {arr2(inertia)};   // body frame, about the CoM

// Per dof
constexpr int DOF_BODY[NV] = {iarr(dof_body)};
constexpr double ARMATURE[NV] = {arr(m.dof_armature)};

constexpr double GRAVITY[3] = {arr(m.opt.gravity)};

// Keyframe 0 ("home") standing pose, for tests and firmware bring-up
constexpr double HOME_QPOS[NQ] = {arr(m.key_qpos[0] if m.nkey else m.qpos0)};

}}  // namespace model
}}  // namespace wbc
"""


def params_header(c):
    P = c._make_params()
    lines = ["// GENERATED by tools/gen_robot_model.py. Do not edit.",
             "// Default WbcParams for targets without Python (values from",
             "// controllers/wbc/wbc_controller.py at generation time).",
             "#pragma once",
             '#include "wbc_params.h"',
             "",
             "static const WbcParams WBC_DEFAULT_PARAMS = {"]
    for name, typ in P._fields_:
        v = getattr(P, name)
        if hasattr(v, "__len__"):
            vals = list(v)
            if typ._type_ in ("i",) or "int" in str(typ._type_):
                body = ", ".join(str(int(x)) for x in vals)
            else:
                body = ", ".join(fmt(x) for x in vals)
            lines.append(f"    /* {name} */ {{{body}}},")
        else:
            lines.append(f"    /* {name} */ {fmt(v) if isinstance(v, float) else int(v)},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--xml", default=os.path.join(ROOT, "CAD", "scene.xml"))
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "wbc"))
    args = ap.parse_args()
    m = mujoco.MjModel.from_xml_path(args.xml)
    src = os.path.relpath(args.xml, ROOT)
    with open(os.path.join(args.out, "robot_model.h"), "w") as f:
        f.write(model_header(m, src))
    from controllers.wbc.wbc_controller import PyWholeBodyController
    c = PyWholeBodyController(m)
    import controllers.wbc.wbc_controller as W
    c._make_params = W.WholeBodyController._make_params.__get__(c)
    with open(os.path.join(args.out, "wbc_default_params.h"), "w") as f:
        f.write(params_header(c))
    print(f"wrote robot_model.h and wbc_default_params.h ({m.nbody} bodies, nv={m.nv}, nu={m.nu})")


if __name__ == "__main__":
    main()
